#!/usr/bin/env python3
"""Writes native/core/qrss/pyunicode_tables.hpp: the Unicode tables the
port reads text through as CPython does. Two are what int() and float()
read text through (_PyUnicode_TransformDecimalAndSpaceToASCII): the code
points past ASCII that are whitespace (Py_UNICODE_ISSPACE, str.isspace)
and the decimal digits (Py_UNICODE_TODECIMAL, str.isdecimal,
unicodedata.decimal), as runs of consecutive code points whose values
count up by one. The third is str.upper()'s full case mapping
(SpecialCasing included, so U+00DF is "SS"): every code point whose
upper() is not itself, with that upper case as UTF-8 (qrss_decode.py's
parse_key upper-cases the callsign of --key).

Generated from the running Python, whose Unicode database version the
header records: regenerate when the Python the reference runs on moves to a
new Unicode version (3.13 has 15.1.0). The C++ (pynum.cpp, decode.cpp) uses the tables;
native/tests/qrss/test_pynum_unicode.cpp and
tests/test_qrss_native_pynum.py hold it against int() and float(),
tests/test_qrss_native_decode.py against str.upper().

    python tools/gen_qrss_unicode_tables.py    # rewrites the header
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "native" / "core" / "qrss" / "pyunicode_tables.hpp"


def tables():
    spaces = [c for c in range(127, 0x110000) if chr(c).isspace()]
    runs = []
    for c in range(127, 0x110000):
        ch = chr(c)
        if not ch.isdecimal():
            continue
        v = unicodedata.decimal(ch)
        assert int(ch) == v, hex(c)
        if runs and runs[-1][1] == c - 1 and runs[-1][2] + (c - runs[-1][0]) == v:
            runs[-1][1] = c
        else:
            runs.append([c, c, v])
    return spaces, runs


def upper_table():
    out = []
    for c in range(0x110000):
        if 0xD800 <= c <= 0xDFFF:
            continue
        u = chr(c).upper()
        if u != chr(c):
            out.append((c, u.encode("utf-8")))
    return out


def c_string(b: bytes) -> str:
    return "".join(chr(x) if 32 <= x < 127 and chr(x) not in '"\\?' else f"\\x{x:02x}\"\"" for x in b)


def main():
    spaces, runs = tables()
    upper = upper_table()
    lines = [
        "// GENERATED by tools/gen_qrss_unicode_tables.py -- do not edit; regenerate with",
        "//   python tools/gen_qrss_unicode_tables.py",
        f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "//",
        "// The code points past ASCII that int() and float() read as a space",
        "// (Py_UNICODE_ISSPACE) and as a decimal digit (Py_UNICODE_TODECIMAL),",
        "// as _PyUnicode_TransformDecimalAndSpaceToASCII maps them; and",
        "// str.upper()'s full case mapping of every code point it changes.",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace sstvae::qrss::pyunicode {",
        "",
        f'inline constexpr const char* UNICODE_VERSION = "{unicodedata.unidata_version}";',
        "",
        f"inline constexpr std::uint32_t SPACES[{len(spaces)}] = {{",
    ]
    for k in range(0, len(spaces), 8):
        lines.append("    " + ", ".join(f"0x{c:05X}" for c in spaces[k:k + 8]) + ",")
    lines += [
        "};",
        "",
        "// [first, last] and the digit value of `first`; each next code point is one more.",
        "struct DigitRun {",
        "    std::uint32_t first;",
        "    std::uint32_t last;",
        "    int value;",
        "};",
        "",
        f"inline constexpr DigitRun DIGITS[{len(runs)}] = {{",
    ]
    for a, b, v in runs:
        lines.append(f"    {{0x{a:05X}, 0x{b:05X}, {v}}},")
    lines += [
        "};",
        "",
        "// str.upper() of `cp` (UTF-8, one to three code points), for every code point",
        "// whose upper case is not itself; ascending by cp.",
        "struct Upper {",
        "    std::uint32_t cp;",
        "    const char* utf8;",
        "};",
        "",
        f"inline constexpr Upper UPPER[{len(upper)}] = {{",
    ]
    for c, u in upper:
        lines.append(f'    {{0x{c:05X}, "{c_string(u)}"}},')
    lines += ["};", "", "}  // namespace sstvae::qrss::pyunicode", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}: {len(spaces)} spaces, {len(runs)} digit runs, {len(upper)} upper cases",
          file=sys.stderr)


if __name__ == "__main__":
    main()
