def c_literal(s: str) -> str:
    """A C++ string literal holding s's UTF-8 bytes (surrogates surrogatepass)."""
    out = []
    for b in s.encode("utf-8", "surrogatepass"):
        if 32 <= b < 127 and chr(b) not in '"\\?':
            out.append(chr(b))
        else:
            out.append(f"\\x{b:02x}\"\"")
    return '"' + "".join(out) + '"'


def main() -> None:
    lines = [
        "// GENERATED by native/tests/qrss/gen_pyjson_pins.py from Python's json.dumps.",
        "// Do not edit by hand.",
        "#pragma once",
        "",
        "#include <optional>",
        "",
        "namespace pyjson_pins {",
        "",
        "struct Layout {",
        "    std::optional<int> indent;",
        "    bool sort_keys;",
        "};",
        "",
        "inline const Layout LAYOUTS[] = {",
    ]
    for ind, srt in LAYOUTS:
        lines.append(f"    {{{'std::nullopt' if ind is None else ind}, {'true' if srt else 'false'}}},")
    lines += ["};", f"inline constexpr int N_LAYOUTS = {len(LAYOUTS)};", "",
              "struct Case {", "    const char* name;", "    const char* input;   // json.dumps(value)",
              f"    const char* want[{len(LAYOUTS)}];", "};", "", "inline const Case CASES[] = {"]
    for name, value in CASES.items():
        lines.append(f"    {{{c_literal(name)},")
        lines.append(f"     {c_literal(json.dumps(value))},")
        lines.append("     {")
        for ind, srt in LAYOUTS:
            lines.append(f"         {c_literal(json.dumps(value, indent=ind, sort_keys=srt))},")
        lines.append("     }},")
    lines += ["};", "", "}  // namespace pyjson_pins", ""]
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    assert not math.isnan(0.0)
    main()
