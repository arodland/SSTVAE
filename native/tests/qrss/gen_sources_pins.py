#!/usr/bin/env python3
"""Writes native/tests/qrss/sources_pins.hpp: streams of (chunk length, read
time) run through sstvae/qrss/live.py's Stamper, for test_sources.cpp to
replay through the C++ port.

Each pushed chunk's samples are its running sample numbers (0, 1, 2, ...
across the stream), so an output chunk is pinned by its first sample, its
length and its time: the C++ checks the samples are that run. Times are
pinned as hex floats (float.hex), so the C++ compares them bit for bit.

    PYTHONPATH=. python native/tests/qrss/gen_sources_pins.py    # rewrites the header
"""

import math
import random
import sys
from pathlib import Path

import numpy as np

from sstvae.qrss import live

FS = 8000
OUT = Path(__file__).resolve().parent / "sources_pins.hpp"


def scenarios():
    T = 1_000_000.0
    yield "steady", live.STAMP_HOLD_S, [(2000, T + (k + 1) * 0.25) for k in range(40)]
    # the app's audio pump held up 3 s, then the 3 s at once (test_qrss_live's burst test)
    yield "burst", live.STAMP_HOLD_S, (
        [(2000, T + (k + 1) * 0.25) for k in range(80)]
        + [(2000, T + 23.0 + 1e-4 * k) for k in range(12)]
        + [(2000, T + 23.0 + (k + 1) * 0.25) for k in range(40)])
    yield "gap", live.STAMP_HOLD_S, (
        [(2000, T + (k + 1) * 0.25) for k in range(80)]
        + [(2000, T + 30.0 + (k + 1) * 0.25) for k in range(80)])
    yield "startup", live.STAMP_HOLD_S, (
        [(2000, T + 8.0 + 1e-4 * k) for k in range(32)]
        + [(2000, T + 8.0 + (k + 1) * 0.25) for k in range(40)])
    yield "hold0", 0.0, [(n, T + 0.1 * k) for k, n in enumerate([1, 0, 7, 2000, 3, 0, 1])]
    # times on half-sample boundaries: round() to even
    yield "halves", 0.0, [(3, (k + 0.5) / FS) for k in range(8000, 8040, 3)] + \
        [(1, 2.5 / FS), (1, 3.5 / FS), (1, -0.5 / FS), (1, -1.5 / FS)]
    # start - next at RESYNC_S * FS exactly, either side
    for d in (-1, 0, 1):
        r = int(live.RESYNC_S * FS)
        yield f"resync{d:+d}", live.STAMP_HOLD_S, [
            (100, 1000.0), (100, 1006.0), (100, (1006.0 * FS + r + d + 100) / FS), (5, 1006.5)]
    rng = random.Random(4242)
    for case in range(6):
        heard = rng.uniform(1e9, 2e9)
        pushes = []
        for _ in range(rng.randint(20, 60)):
            n = rng.choice([0, 1, rng.randint(1, 4000), 2000])
            heard += n / FS
            kind = rng.random()
            if kind < 0.15:
                late = rng.uniform(0.1, 7.0)
                for _ in range(rng.randint(1, 8)):
                    m = rng.randint(1, 3000)
                    heard += m / FS
                    pushes.append((m, heard + late))
                continue
            if kind < 0.25:
                heard += rng.uniform(0.5, 15.0)
            pushes.append((n, heard + rng.uniform(0, 0.02)))
        yield f"random{case}", rng.choice([live.STAMP_HOLD_S, 1.0, 0.0]), pushes


def run(hold, pushes):
    st = live.Stamper(hold)
    outs, at = [], 0
    for k, (n, t) in enumerate(pushes):
        x = np.arange(at, at + n, dtype=np.float64)
        at += n
        for y, te in st.push(x, t):
            outs.append((k, int(y[0]) if len(y) else -1, len(y), te))
    for y, te in st.flush():
        outs.append((-1, int(y[0]) if len(y) else -1, len(y), te))
    return outs


def main():
    lines = [
        "// GENERATED by native/tests/qrss/gen_sources_pins.py from sstvae/qrss/live.py's",
        "// Stamper -- do not edit; regenerate with",
        "//   PYTHONPATH=. python native/tests/qrss/gen_sources_pins.py",
        "",
        "#pragma once",
        "",
        "#include <vector>",
        "",
        "namespace sources_pins {",
        "",
        "struct Push {",
        "    long long n;",
        "    double t;",
        "};",
        "",
        "// After push `after` (-1: the final flush), a chunk of `len` samples",
        "// starting at running sample `first` (-1 when empty), at `t_end`.",
        "struct Out {",
        "    int after;",
        "    long long first;",
        "    long long len;",
        "    double t_end;",
        "};",
        "",
        "struct Case {",
        "    const char* name;",
        "    double hold_s;",
        "    std::vector<Push> pushes;",
        "    std::vector<Out> outs;",
        "};",
        "",
        "inline const std::vector<Case>& cases() {",
        "    static const std::vector<Case> c = {",
    ]
    for name, hold, pushes in scenarios():
        outs = run(hold, pushes)
        lines.append(f'        {{"{name}", {float(hold).hex()},')
        lines.append("         {" + ", ".join(f"{{{n}, {float(t).hex()}}}" for n, t in pushes) + "},")
        lines.append("         {" + ", ".join(f"{{{k}, {f}, {n}, {te.hex()}}}" for k, f, n, te in outs)
                     + "}},")
    lines += ["    };", "    return c;", "}", "", "}  // namespace sources_pins", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
