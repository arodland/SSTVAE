#!/usr/bin/env python3
"""Writes native/tests/qrss/pynum_unicode_pins.hpp: int() and float() of
text holding Unicode spaces and decimal digits, as Python 3.13 parses them,
for test_pynum_unicode.cpp to hold native/core/qrss/pynum against.

Every Unicode space and the first and last digit of every decimal-digit
run (pyunicode_tables.hpp's), each inside, before and after an ASCII
number, plus characters Python refuses (DEL, U+00AD, U+200B, \\x1c, a
fullwidth letter, a superscript two, a lone surrogate's bytes, bytes that
are not UTF-8). Texts are pinned as their UTF-8 bytes (C escapes), results
as str(int(text)) (base 10 and 16) and float.hex, or "" for a ValueError.

    python native/tests/qrss/gen_pynum_unicode_pins.py    # rewrites the header
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent / "pynum_unicode_pins.hpp"


def texts():
    spaces = [c for c in range(127, 0x110000) if chr(c).isspace()]
    digits = []
    prev = None
    for c in range(127, 0x110000):
        if chr(c).isdecimal():
            if prev is None or prev != c - 1:
                digits.append(c)
            prev = c
    # first and last of each run
    ends = []
    for c in range(127, 0x110000):
        ch = chr(c)
        if ch.isdecimal() and (not chr(c - 1).isdecimal() or not chr(c + 1).isdecimal()):
            ends.append(c)
    out = []
    for c in spaces:
        s = chr(c)
        out += [s + "12" + s, "1" + s + "2", s + "1.5e3" + s, s + "-0x1f" + s]
    for c in ends:
        d = chr(c)
        out += [d, "1" + d, d + "_" + d, "-" + d + "." + d + "e" + d, "0x" + d + "f", "\u3000" + d + "\u00a0"]
    out += ["\x7f1", "1\x7f", "\u00ad1", "1\u200b", "\x1c1", "\uff21", "\u00b2", "1\u00b2",
            "\u0660x10", "inf\u2003", "\u2003nan", "\uff11\uff10\uff10", "\u0661_\u0662"]
    return out


def c_escape(b: bytes) -> str:
    return "".join(chr(x) if 32 <= x < 127 and chr(x) not in '"\\?' else f"\\x{x:02x}\"\"" for x in b)


def result_int(t, base):
    try:
        return str(int(t, base))
    except ValueError:
        return ""


def result_float(t):
    try:
        return float(t).hex()
    except ValueError:
        return ""


def main():
    rows = []
    for t in texts():
        rows.append((t.encode("utf-8"), result_int(t, 10), result_int(t, 16), result_float(t)))
    # bytes that are not UTF-8, and a lone surrogate's encoding (surrogatepass)
    for b in (b"1\xff", b"\xc0\xb1", b"\xed\xa0\x80" b"1", b"1\xe2\x80"):
        rows.append((b, "", "", ""))
    lines = [
        "// GENERATED by native/tests/qrss/gen_pynum_unicode_pins.py -- do not edit; regenerate with",
        "//   python native/tests/qrss/gen_pynum_unicode_pins.py",
        f"// Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "",
        "#pragma once",
        "",
        "#include <vector>",
        "",
        "namespace pynum_unicode_pins {",
        "",
        "// text (UTF-8), str(int(text, 10)), str(int(text, 16)), float(text).hex(); \"\" = ValueError",
        "struct Row {",
        "    const char* text;",
        "    const char* int10;",
        "    const char* int16;",
        "    const char* flt;",
        "};",
        "",
        "inline const std::vector<Row>& rows() {",
        "    static const std::vector<Row> r = {",
    ]
    for b, i10, i16, f in rows:
        lines.append(f'        {{"{c_escape(b)}", "{i10}", "{i16}", "{f}"}},')
    lines += ["    };", "    return r;", "}", "", "}  // namespace pynum_unicode_pins", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}: {len(rows)} rows", file=sys.stderr)


if __name__ == "__main__":
    main()
