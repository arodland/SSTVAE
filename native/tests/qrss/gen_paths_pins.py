#!/usr/bin/env python3
"""The pins of native/tests/qrss/test_paths.cpp, from CPython's own codecs and pathlib.

Writes native/tests/qrss/paths_pins.hpp, which is committed so the ctest
needs no Python. Re-run it from the repository root if the families below
change:

    python native/tests/qrss/gen_paths_pins.py

native/core/util/fileio.hpp converts a UTF-8 file name to UTF-16 as Python
does on Windows (PEP 529: "utf-8" with "surrogatepass"), so the pins are
CPython's answers over byte strings enumerated identically on both sides:

- every code point, one at a time: chr(cp).encode("utf-8", "surrogatepass")
  (what utf8_of writes for that code point's UTF-16) and its UTF-16LE;
- every byte string of one and two bytes, every three-byte string starting
  E0..EF, and four-byte strings starting F0..F4 with every second byte and
  the third and fourth from EDGES: each decoded with
  bytes.decode("utf-8", "surrogatepass"), recorded as b"\\x01" + one length
  byte + the UTF-16LE when it decodes and b"\\x00" when it raises.

The ctest hashes its own records the same way and compares SHA-256s, and the
accepted counts, so a disagreement says which family it is in.

Then str(PurePosixPath(text)), .name and .suffix for the texts in PATHS
(native/core/qrss/pypath.hpp: how sstvae-qrss and the codec glue spell a
path as qrss_*.py prints it), as UTF-8.

And pypath::stderr_text, what the scripts' sys.stderr writes for a message
naming a file by its bytes, over the same three families: each string's
os.fsdecode encoded as stderr encodes ("utf-8", "backslashreplace"),
recorded as two length bytes (little-endian) and the bytes. POSIX decodes
with "surrogateescape"; Windows with "surrogatepass" (PEP 529), and since
that refuses what is not a surrogate either, the Windows digest escapes the
rest a byte at a time as "surrogateescape" would (a name sstvae-qrss is
given on Windows is always UTF-8 but for lone surrogates).
"""

from __future__ import annotations

import codecs
import hashlib
import sys
from pathlib import Path, PurePosixPath

OUT = Path(__file__).with_name("paths_pins.hpp")
EDGES = (0x00, 0x7F, 0x80, 0x9F, 0xA0, 0xBF, 0xC0, 0xFF)
PATHS = [
    "", ".", "./", "/", "//", "///", "////a", "//a", "//a//b", "a//b/", "./a/./b", "a/../b", "/./x",
    "x/.", "~/x", "a/b/", "a.", ".onnx", "a.b.", "x/.a.pt", "a..pt", "foo.PT", "a.pt/", "a.tar.gz",
    "a/b.c/d", "..", "a/..", "...", "..a", "a/.", "m/", "rx.NPZ", "x/y.npz/", "\u00e9/\u00f1.onnx",
    "m\u00fcde.pt", "sp ace/x y.onnx", "\u65e5\u672c/\u8a9e.wav", "a\\b.wav", "\U0001f600.wav",
    "caf\udce9.wav", "/tmp/\udcff\udcfe/x.npz",
]


def code_points() -> tuple[str, str]:
    enc, u16 = hashlib.sha256(), hashlib.sha256()
    for cp in range(0x110000):
        enc.update(chr(cp).encode("utf-8", "surrogatepass"))
        u16.update(chr(cp).encode("utf-16-le", "surrogatepass"))
    return enc.hexdigest(), u16.hexdigest()


def family(strings) -> tuple[str, int, int]:
    h, n, ok = hashlib.sha256(), 0, 0
    for b in strings:
        n += 1
        try:
            s = b.decode("utf-8", "surrogatepass")
        except UnicodeDecodeError:
            h.update(b"\x00")
            continue
        u = s.encode("utf-16-le", "surrogatepass")
        h.update(b"\x01" + bytes([len(u)]) + u)
        ok += 1
    return h.hexdigest(), n, ok


def _pass_then_escape(exc: UnicodeDecodeError):
    b, s = exc.object, exc.start
    if b[s] == 0xED and s + 2 < len(b) and 0xA0 <= b[s + 1] <= 0xBF and 0x80 <= b[s + 2] <= 0xBF:
        return chr(((b[s] & 0x0F) << 12) | ((b[s + 1] & 0x3F) << 6) | (b[s + 2] & 0x3F)), s + 3
    return chr(0xDC00 + b[s]), s + 1


codecs.register_error("sstvae_pass_then_escape", _pass_then_escape)


def stderr_family(strings, errors: str) -> str:
    h = hashlib.sha256()
    for b in strings:
        out = b.decode("utf-8", errors).encode("utf-8", "backslashreplace")
        h.update(len(out).to_bytes(2, "little") + out)
    return h.hexdigest()


def one_two():
    for a in range(256):
        yield bytes([a])
    for a in range(256):
        for b in range(256):
            yield bytes([a, b])


def three():
    for a in range(0xE0, 0xF0):
        for b in range(256):
            for c in range(256):
                yield bytes([a, b, c])


def four():
    for a in range(0xF0, 0xF5):
        for b in range(256):
            for c in EDGES:
                for d in EDGES:
                    yield bytes([a, b, c, d])


def c_string(text: str) -> str:
    """A C++ literal of text's UTF-8 (os.fsencode's bytes for a surrogate escape)."""
    b = text.encode("utf-8", "surrogateescape")
    # octal escapes: three digits at most, so the next character never joins one
    return '"' + "".join(f"\\{c:03o}" if c >= 0x80 or c < 0x20 or c in b'"\\' else chr(c) for c in b) + '"'


def main() -> None:
    enc, u16 = code_points()
    fams = [("ONE_TWO", one_two()), ("THREE", three()), ("FOUR", four())]
    lines = [
        "// GENERATED by native/tests/qrss/gen_paths_pins.py from CPython's codecs and pathlib",
        f"// (CPython {sys.version.split()[0]}). Do not edit.",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace paths_pins {",
        "",
        "// every code point: its UTF-8 (surrogatepass) and its UTF-16LE",
        f'constexpr const char* CODE_POINTS_UTF8 = "{enc}";',
        f'constexpr const char* CODE_POINTS_UTF16 = "{u16}";',
        "",
        "// byte-string families: digest of the records, strings, accepted",
    ]
    for name, it in fams:
        d, n, ok = family(it)
        lines.append(f'constexpr const char* {name}_DIGEST = "{d}";')
        lines.append(f"constexpr std::size_t {name}_COUNT = {n};")
        lines.append(f"constexpr std::size_t {name}_ACCEPTED = {ok};")
    lines += ["", "// stderr_text's families: POSIX (surrogateescape), Windows (surrogatepass first)"]
    for name, make in [("ONE_TWO", one_two), ("THREE", three), ("FOUR", four)]:
        lines.append(f'constexpr const char* STDERR_{name}_POSIX = "{stderr_family(make(), "surrogateescape")}";')
        lines.append(f'constexpr const char* STDERR_{name}_WINDOWS = '
                     f'"{stderr_family(make(), "sstvae_pass_then_escape")}";')
    lines.append("")
    lines.append("constexpr unsigned char EDGES[] = {" + ", ".join(f"0x{e:02X}" for e in EDGES) + "};")
    lines += ["", "// str(PurePosixPath(text)), .name, .suffix", "struct PathPin {",
              "    const char *text, *str, *name, *suffix;", "};", "constexpr PathPin PATHS[] = {"]
    for t in PATHS:
        p = PurePosixPath(t)
        lines.append(f"    {{{c_string(t)}, {c_string(str(p))}, {c_string(p.name)}, {c_string(p.suffix)}}},")
    lines.append("};")
    lines += ["", "}  // namespace paths_pins", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
