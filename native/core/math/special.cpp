// --- polevl.h ---------------------------------------------------------------

double polevl(double x, const double coef[], int N) {
    const double* p = coef;
    double ans = *p++;
    int i = N;
    do {
        ans = ans * x + *p++;
    } while (--i);
    return ans;
}

double p1evl(double x, const double coef[], int N) {
    const double* p = coef;
    double ans = x + *p++;
    int i = N - 1;
    do
        ans = ans * x + *p++;
    while (--i);
    return ans;
}

double ratevl(double x, const double num[], int M, const double denom[], int N) {
    int i, dir;
    double y, num_ans, denom_ans;
    double absx = std::abs(x);
    const double* p;

    if (absx > 1) {
        dir = -1;
        p = num + M;
        y = 1 / x;
    } else {
        dir = 1;
        p = num;
        y = x;
    }
    num_ans = *p;
    p += dir;
    for (i = 1; i <= M; i++) {
        num_ans = num_ans * y + *p;
        p += dir;
    }
    if (absx > 1) {
        p = denom + N;
    } else {
        p = denom;
    }
    denom_ans = *p;
    p += dir;
    for (i = 1; i <= N; i++) {
        denom_ans = denom_ans * y + *p;
        p += dir;
    }
    if (absx > 1) {
        i = M - N;
        return std::pow(x, i) * num_ans / denom_ans;
    }
    return num_ans / denom_ans;
}

// --- trig.h -----------------------------------------------------------------

double sinpi(double x) {
    double s = 1.0;
    if (std::signbit(x)) {
        x = -x;
        s = -1.0;
    }
    double r = std::fmod(x, 2.0);
    if (r < 0.5) return s * std::sin(XSF_PI * r);
    if (r > 1.5) return s * std::sin(XSF_PI * (r - 2.0));
    return -s * std::sin(XSF_PI * (r - 1.0));
}

