double py_sinpi(double x) {
    const double y = std::fmod(std::abs(x), 2.0);
    const int n = static_cast<int>(std::round(2.0 * y));   // C round (half away from zero), as CPython's
    double r = NaN;
    switch (n) {
        case 0: r = std::sin(PY_PI * y); break;
        case 1: r = std::cos(PY_PI * (y - 0.5)); break;
        // N.B. -sin(pi*(y-1.0)) is *not* equivalent: it would give -0.0
        // instead of 0.0 when y == 1.0.
        case 2: r = std::sin(PY_PI * (1.0 - y)); break;
        case 3: r = -std::cos(PY_PI * (y - 1.5)); break;
        case 4: r = std::sin(PY_PI * (y - 2.0)); break;
        default: break;
    }
    return std::copysign(1.0, x) * r;
}

// Lanczos' sum L_g(x), for positive x.
double lanczos_sum(double x) {
    double num = 0.0, den = 0.0;
    if (x < 5.0) {
        for (int i = LANCZOS_N; --i >= 0;) {
            num = num * x + lanczos_num_coeffs[i];
            den = den * x + lanczos_den_coeffs[i];
        }
    } else {
        for (int i = 0; i < LANCZOS_N; i++) {
            num = num / x + lanczos_num_coeffs[i];
            den = den / x + lanczos_den_coeffs[i];
        }
    }
    return num / den;
}

