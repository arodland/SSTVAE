double ndtri(double y0) {
    double x, y, z, y2, x0, x1;
    int code;

    if (y0 == 0.0) return -INF;
    if (y0 == 1.0) return INF;
    if (y0 < 0.0 || y0 > 1.0) return NaN;
    code = 1;
    y = y0;
    if (y > (1.0 - 0.13533528323661269189)) { /* 0.135... = exp(-2) */
        y = 1.0 - y;
        code = 0;
    }

    if (y > 0.13533528323661269189) {
        y = y - 0.5;
        y2 = y * y;
        x = y + y * (y2 * polevl(y2, ndtri_P0, 4) / p1evl(y2, ndtri_Q0, 8));
        x = x * SQRT2PI;
        return x;
    }

    x = std::sqrt(-2.0 * std::log(y));
    x0 = x - std::log(x) / x;

    z = 1.0 / x;
    if (x < 8.0) { /* y > exp(-32) = 1.2664165549e-14 */
        x1 = z * polevl(z, ndtri_P1, 8) / p1evl(z, ndtri_Q1, 8);
    } else {
        x1 = z * polevl(z, ndtri_P2, 8) / p1evl(z, ndtri_Q2, 8);
    }
    x = x0 - x1;
    if (code != 0) x = -x;
    return x;
}

double norm_isf(double q) {
    // rv_continuous.isf: 0 < q < 1 -> _isf(q) * scale + loc; q == 1 -> the
    // support's lower end, q == 0 its upper end; anything else badvalue.
    if (q > 0.0 && q < 1.0) return -ndtri(q) * 1.0 + 0.0;
    if (q == 1.0) return -INF;
    if (q == 0.0) return INF;
    return NaN;
}

double gamma_logsf(double x, double a) {
    // rv_continuous.logsf: the output starts at -inf; badvalue (NaN) where
    // the shape fails _argcheck (a > 0) or x is NaN; 0 where x <= the
    // support's lower end (0); _logsf inside the open support (0, inf).
    if (!(a > 0.0) || std::isnan(x)) return NaN;
    if (x <= 0.0) return 0.0;
    if (!(x < INF)) return -INF;
    // rv_continuous._logsf: apply_where(x > median, log(sf), log1p(-cdf))
    const double median = gammaincinv(a, 0.5);   // gamma_gen._ppf(0.5, a)
    if (x > median) return std::log(gammaincc(a, x));
    return std::log1p(-gammainc(a, x));
}

double py_lgamma(double x) {
    if (!std::isfinite(x)) {
        if (std::isnan(x)) return x;   // lgamma(nan) = nan
        return INF;                    // lgamma(+-inf) = +inf
    }
    // integer arguments
    if (x == std::floor(x) && x <= 2.0) {
        if (x <= 0.0) return INF;   // Python: ValueError (EDOM)
        return 0.0;                 // lgamma(1) = lgamma(2) = 0.0
    }
    const double absx = std::abs(x);
    // tiny arguments: lgamma(x) ~ -log(fabs(x)) for small x
    if (absx < 1e-20) return -std::log(absx);
    double r = std::log(lanczos_sum(absx)) - py_lanczos_g;
    r += (absx - 0.5) * (std::log(absx + py_lanczos_g - 0.5) - 1);
    if (x < 0.0) r = PY_LOGPI - std::log(std::abs(py_sinpi(absx))) - std::log(absx) - r;
    return r;
}

