double cephes_erfc(double a) {
    double p, q, x, y, z;

    if (std::isnan(a)) return NaN;
    if (a < 0.0) {
        x = -a;
    } else {
        x = a;
    }
    if (x < 1.0) return 1.0 - cephes_erf(a);

    z = -a * a;
    if (z < -MAXLOG) goto under;
    z = std::exp(z);
    if (x < 8.0) {
        p = polevl(x, ndtr_P, 8);
        q = p1evl(x, ndtr_Q, 8);
    } else {
        p = polevl(x, ndtr_R, 5);
        q = p1evl(x, ndtr_S, 6);
    }
    y = (z * p) / q;
    if (a < 0) y = 2.0 - y;
    if (y != 0.0) return y;

under:
    if (a < 0) return 2.0;
    return 0.0;
}

double cephes_erf(double x) {
    double y, z;
    if (std::isnan(x)) return NaN;
    if (x < 0.0) return -cephes_erf(-x);
    if (std::abs(x) > 1.0) return 1.0 - cephes_erfc(x);
    z = x * x;
    y = x * polevl(z, ndtr_T, 4) / p1evl(z, ndtr_U, 5);
    return y;
}

