double cephes_log1p(double x) {
    double z = 1.0 + x;
    if ((z < XSF_SQRT1_2) || (z > XSF_SQRT2)) return std::log(z);
    z = x * x;
    z = -0.5 * z + x * (z * polevl(x, unity_LP, 6) / p1evl(x, unity_LQ, 6));
    return x + z;
}

double log1pmx(double x) {
    if (std::abs(x) < 0.5) {
        std::uint64_t n;
        double xfac = x;
        double term;
        double res = 0;
        for (n = 2; n < MAXITER; n++) {
            xfac *= -x;
            term = xfac / static_cast<double>(n);
            res += term;
            if (std::abs(term) < MACHEP * std::abs(res)) break;
        }
        return res;
    }
    return cephes_log1p(x) - x;
}

constexpr double unity_EP[3] = {
    1.2617719307481059087798E-4,
    3.0299440770744196129956E-2,
    9.9999999999999999991025E-1,
};
constexpr double unity_EQ[4] = {
    3.0019850513866445504159E-6,
    2.5244834034968410419224E-3,
    2.2726554820815502876593E-1,
    2.0000000000000000000897E0,
};

double cephes_expm1(double x) {
    double r, xx;
    if (!std::isfinite(x)) {
        if (std::isnan(x)) return x;
        if (x > 0) return x;
        return -1.0;
    }
    if ((x < -0.5) || (x > 0.5)) return std::exp(x) - 1.0;
    xx = x * x;
    r = x * polevl(xx, unity_EP, 2);
    r = r / (polevl(xx, unity_EQ, 3) - r);
    return r + r;
}

double lgam1p_taylor(double x) {
    int n;
    double xfac, coeff, res;
    if (x == 0) return 0;
    res = -SCIPY_EULER * x;
    xfac = -x;
    for (n = 2; n < 42; n++) {
        xfac *= -x;
        coeff = zeta_(n, 1) * xfac / n;
        res += coeff;
        if (std::abs(coeff) < MACHEP * std::abs(res)) break;
    }
    return res;
}

double lgam1p(double x) {
    if (std::abs(x) <= 0.5) return lgam1p_taylor(x);
    if (std::abs(x - 1) < 0.5) return std::log(x) + lgam1p_taylor(x - 1);
    return lgam_(x + 1);
}

