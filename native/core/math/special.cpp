constexpr double zeta_A[] = {12.0,
                             -720.0,
                             30240.0,
                             -1209600.0,
                             47900160.0,
                             -1.8924375803183791606e9,
                             7.47242496e10,
                             -2.950130727918164224e12,
                             1.1646782814350067249e14,
                             -4.5979787224074726105e15,
                             1.8152105401943546773e17,
                             -7.1661652561756670113e18};

double zeta_(double x, double q) {
    int i;
    double a, b, k, s, t, w;

    if (x == 1.0) goto retinf;
    if (x < 1.0) {
    domerr:
        return NaN;
    }
    if (q <= 0.0) {
        if (q == std::floor(q)) {
        retinf:
            return INF;
        }
        if (x != std::floor(x)) goto domerr;
    }
    if (q > 1e8) {
        return (1 / (x - 1) + 1 / (2 * q)) * std::pow(q, 1 - x);
    }

    s = std::pow(q, -x);
    a = q;
    i = 0;
    b = 0.0;
    while ((i < 9) || (a <= 9.0)) {
        i += 1;
        a += 1.0;
        b = std::pow(a, -x);
        s += b;
        if (std::abs(b / s) < MACHEP) goto done;
    }

    w = a;
    s += b * w / (x - 1.0);
    s -= 0.5 * b;
    a = 1.0;
    k = 0.0;
    for (i = 0; i < 12; i++) {
        a *= x + k;
        b /= w;
        t = a * b / zeta_A[i];
        s = s + t;
        t = std::abs(t / s);
        if (t < MACHEP) goto done;
        k += 1.0;
        a *= x + k;
        b /= w;
        k += 1.0;
    }
done:
    return s;
}

